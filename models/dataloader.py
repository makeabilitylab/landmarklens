"""
PyTorch dataloader for panoramic images and gaze heatmap targets.

Data layout:
    npy:   {npy_root}/{group}/{region}/{route_id}/{sequence}/{frame}.npy
    pano:  {panorama_root}/{sequence}/{frame}.jpg
"""

import json
import random
import warnings
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_JSON = BASE_DIR / "web" / "data.json"


def _load_orientation_lookup() -> dict[str, tuple[float, float]]:
    """Build {frame_stem: (yaw, pitch)} from web/data.json.

    Used to rotate panorama images so the viewing direction is centered,
    matching the coordinate system of heatmaps generated by
    generate_route_heatmaps.py.
    """
    if not DATA_JSON.exists():
        warnings.warn(f"{DATA_JSON} not found - panoramas will not be orientation-corrected")
        return {}
    with open(DATA_JSON) as f:
        data = json.load(f)
    lookup: dict[str, tuple[float, float]] = {}
    for frame in data.get("frames", []):
        filename = frame.get("filename", "")
        stem = Path(filename).stem
        lookup[stem] = (frame.get("yaw", 0.0), frame.get("pitch", 0.0))
    return lookup


def rotate_panorama(image: np.ndarray, frame_stem: str,
                    orientation_lookup: dict, is_reverse: bool = False) -> np.ndarray:
    """Horizontally roll a panorama so the walking direction is centered.

    Works on numpy arrays of any shape (..., W) — both (H, W) heatmaps and
    (H, W, C) RGB images.  The roll amount comes from the base yaw in
    *orientation_lookup*; for reverse segments an extra 180° is added so
    the walking direction (opposite to the capture direction) lands at the
    image center.

    Args:
        image: numpy array with width along the last axis for (H, W) or
               axis 1 for (H, W, C).
        frame_stem: filename stem used to look up yaw in orientation_lookup.
        orientation_lookup: {frame_stem: (yaw, pitch)} dict.
        is_reverse: whether this frame belongs to a reverse segment.

    Returns:
        Rolled copy of *image* (or the original if yaw == 0).
    """
    yaw, _pitch = orientation_lookup.get(frame_stem, (0.0, 0.0))
    if is_reverse:
        yaw = (yaw + 180.0) % 360.0
    if yaw == 0.0:
        return image
    width = image.shape[1]  # axis 1 is width for both (H, W) and (H, W, C)
    shift_x = -round(yaw / 360.0 * width)
    return np.roll(image, shift_x, axis=1)


def _discover_samples(npy_root, panorama_root, groups=None, routes=None):
    """Walk the npy directory tree and return a list of sample dicts.

    groups: collection of group names to include (e.g. {"good"}, {"poor"}, or
            None / {"good", "poor"} for both).
    routes: collection of route_id strings to include (e.g. {"ginza_c", "nezu_a"}),
            or None for all routes.
    """
    npy_root = Path(npy_root)
    panorama_root = Path(panorama_root)
    if groups is not None:
        groups = set(groups)
    if routes is not None:
        routes = set(routes)
    samples = []
    missing = 0

    for npy_path in sorted(npy_root.rglob("*.npy")):
        parts = npy_path.relative_to(npy_root).parts
        if len(parts) != 5:
            continue
        group, region, route_id, sequence, frame_file = parts
        if groups is not None and group not in groups:
            continue
        if routes is not None and route_id not in routes:
            continue
        frame = Path(frame_file).stem

        pano_path = panorama_root / sequence / f"{frame}.jpg"
        if not pano_path.exists():
            missing += 1
            continue

        samples.append({
            "npy_path": npy_path,
            "pano_path": pano_path,
            "group": group,
            "region": region,
            "route_id": route_id,
            "sequence": sequence,
            "frame": frame,
        })

    if missing:
        warnings.warn(f"Skipped {missing} samples with missing panorama files")

    return samples


def split_samples(samples, ratios=(0.7, 0.15, 0.15), atomicity="route", seed=42):
    """
    Split samples into train/val/test sets.

    atomicity:
        "route"    - split by (group, route_id), keeping all frames from a route together
        "sequence" - split by (group, sequence), keeping all frames from a sequence together
        "region"   - split by region (greedy bin-packing)
        "none"     - split individual samples
    """
    assert len(ratios) == 3 and abs(sum(ratios) - 1.0) < 1e-6

    rng = random.Random(seed)

    if atomicity == "route":
        groups = defaultdict(list)
        for s in samples:
            groups[(s["group"], s["route_id"])].append(s)
        keys = list(groups.keys())
        rng.shuffle(keys)

        n = len(keys)
        t1 = int(round(n * ratios[0]))
        t2 = int(round(n * (ratios[0] + ratios[1])))

        train_keys, val_keys, test_keys = keys[:t1], keys[t1:t2], keys[t2:]
        train = [s for k in train_keys for s in groups[k]]
        val = [s for k in val_keys for s in groups[k]]
        test = [s for k in test_keys for s in groups[k]]

        split_info = {
            "atomicity": "route",
            "train": {"routes": sorted(train_keys), "n_samples": len(train)},
            "val":   {"routes": sorted(val_keys),   "n_samples": len(val)},
            "test":  {"routes": sorted(test_keys),  "n_samples": len(test)},
        }

    elif atomicity == "sequence":
        groups = defaultdict(list)
        for s in samples:
            groups[(s["group"], s["sequence"])].append(s)
        keys = list(groups.keys())
        rng.shuffle(keys)

        n = len(keys)
        t1 = int(round(n * ratios[0]))
        t2 = int(round(n * (ratios[0] + ratios[1])))

        train_keys, val_keys, test_keys = keys[:t1], keys[t1:t2], keys[t2:]
        train = [s for k in train_keys for s in groups[k]]
        val = [s for k in val_keys for s in groups[k]]
        test = [s for k in test_keys for s in groups[k]]

        split_info = {
            "atomicity": "sequence",
            "train": {"sequences": sorted(train_keys), "n_samples": len(train)},
            "val":   {"sequences": sorted(val_keys),   "n_samples": len(val)},
            "test":  {"sequences": sorted(test_keys),  "n_samples": len(test)},
        }

    elif atomicity == "region":
        groups = defaultdict(list)
        for s in samples:
            groups[s["region"]].append(s)

        total = len(samples)
        targets = [r * total for r in ratios]
        bins = [[] for _ in range(3)]
        bin_regions = [[] for _ in range(3)]
        counts = [0.0, 0.0, 0.0]

        # Sort regions by size descending for greedy bin-packing
        for region in sorted(groups, key=lambda r: len(groups[r]), reverse=True):
            # Assign to the bin furthest below its target proportion
            deficits = [targets[i] - counts[i] for i in range(3)]
            best = deficits.index(max(deficits))
            bins[best].extend(groups[region])
            bin_regions[best].append(region)
            counts[best] += len(groups[region])

        train, val, test = bins

        split_info = {
            "atomicity": "region",
            "train": {"regions": sorted(bin_regions[0]), "n_samples": len(train)},
            "val":   {"regions": sorted(bin_regions[1]), "n_samples": len(val)},
            "test":  {"regions": sorted(bin_regions[2]), "n_samples": len(test)},
        }

    elif atomicity == "none":
        shuffled = list(samples)
        rng.shuffle(shuffled)
        n = len(shuffled)
        t1 = int(round(n * ratios[0]))
        t2 = int(round(n * (ratios[0] + ratios[1])))
        train = shuffled[:t1]
        val = shuffled[t1:t2]
        test = shuffled[t2:]

        split_info = {
            "atomicity": "none",
            "train": {"n_samples": len(train)},
            "val":   {"n_samples": len(val)},
            "test":  {"n_samples": len(test)},
        }

    else:
        raise ValueError(f"Unknown atomicity: {atomicity!r}. Use 'route', 'sequence', 'region', or 'none'.")

    return train, val, test, split_info


class GazeHeatmapDataset(Dataset):
    """
    PyTorch Dataset yielding panoramic images and gaze heatmap targets.

    Each item is a dict with:
        image:    (3, H, W) float tensor in [0, 1]
        heatmap:  (1, H, W) float tensor in [0, 1]
        group:    str ("good" or "poor")
        region:   str
        route_id: str
        frame:    str
    """

    def __init__(self, samples, transform=None, target_size=(960, 1920),
                 orientation_lookup=None):
        self.samples = samples
        self.transform = transform
        self.target_size = target_size  # (H, W)
        self.orientation_lookup = orientation_lookup or {}

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        s = self.samples[idx]

        # Load panorama and rotate so the walking direction is centered
        img = Image.open(s["pano_path"]).convert("RGB")
        img = img.resize((self.target_size[1], self.target_size[0]), Image.BILINEAR)
        img = np.array(img, dtype=np.float32) / 255.0  # (H, W, 3)

        is_reverse = s["sequence"].endswith("_rev")
        img = rotate_panorama(img, s["frame"], self.orientation_lookup, is_reverse)

        if self.transform is not None:
            img = Image.fromarray((img * 255).astype(np.uint8))
            img = self.transform(img)
        else:
            img = torch.from_numpy(img).permute(2, 0, 1)  # (3, H, W)

        # Load heatmap — already in yaw-rotated coordinate system, but
        # reverse segments need an extra 180° to match the panorama rotation
        heatmap = np.load(s["npy_path"]).astype(np.float32)
        if is_reverse:
            heatmap = np.roll(heatmap, heatmap.shape[1] // 2, axis=1)
        if (heatmap.shape[0], heatmap.shape[1]) != self.target_size:
            hm_img = Image.fromarray(heatmap)
            hm_img = hm_img.resize((self.target_size[1], self.target_size[0]), Image.BILINEAR)
            heatmap = np.array(hm_img, dtype=np.float32)
        heatmap = torch.from_numpy(heatmap).unsqueeze(0)  # (1, H, W)

        return {
            "image": img,
            "heatmap": heatmap,
            "group": s["group"],
            "region": s["region"],
            "route_id": s["route_id"],
            "frame": s["frame"],
        }


def get_dataloaders(
    npy_root="study-data/route-heatmaps/combined/npy",
    panorama_root="data/frames",
    ratios=(0.7, 0.15, 0.15),
    atomicity="route",
    seed=42,
    batch_size=8,
    num_workers=4,
    transform=None,
    target_size=(960, 1920),
    groups=None,
    routes=None,
) -> tuple[DataLoader, DataLoader, DataLoader]:
    """Convenience factory returning (train_loader, val_loader, test_loader).

    groups: "good", "poor", or None (both). Also accepts a list/set of values.
    routes: route_id or collection of route_ids to include, or None for all.
    """
    npy_root = BASE_DIR / npy_root
    panorama_root = BASE_DIR / panorama_root

    if isinstance(groups, str):
        groups = {groups}
    if isinstance(routes, str):
        routes = {routes}

    samples = _discover_samples(npy_root, panorama_root, groups=groups, routes=routes)
    if not samples:
        raise RuntimeError(f"No samples found. Check paths:\n  npy: {npy_root}\n  pano: {panorama_root}")

    orientation_lookup = _load_orientation_lookup()

    train_s, val_s, test_s, split_info = split_samples(samples, ratios, atomicity, seed)

    loaders = []
    for split_samples_list, shuffle in [(train_s, True), (val_s, False), (test_s, False)]:
        ds = GazeHeatmapDataset(split_samples_list, transform=transform, target_size=target_size,
                                orientation_lookup=orientation_lookup)
        loaders.append(DataLoader(
            ds,
            batch_size=batch_size,
            shuffle=shuffle,
            num_workers=num_workers,
            pin_memory=True,
        ))

    return tuple(loaders), split_info
